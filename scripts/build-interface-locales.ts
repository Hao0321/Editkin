import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";
import { CORE_MESSAGES } from "../src/ui/i18n/coreMessages";

const directory = resolve("src/ui/i18n");
const rows: ReadonlyArray<readonly string[]>[] = [];
for (const file of (await readdir(directory)).filter(file => /^interfaceMessages\.\d+\.ts$/.test(file)).sort()) {
  rows.push((await import(pathToFileURL(join(directory, file)).href)).INTERFACE_MESSAGES);
}
// The core workflow owns wording for shared labels; packs extend the catalogue.
const catalogue: Record<string, readonly string[]> = {};
const placeholders = (text: string) => [...text.matchAll(/\{[A-Za-z][\w]*\}/g)].map(match => match[0]).sort().join("|");
for (const row of [...rows.flat(), ...CORE_MESSAGES]) {
  if (row.length !== 5 || row.some(text => typeof text !== "string" || !text.length)) throw new Error("Invalid interface message row");
  for (const text of row.slice(1)) if (placeholders(text) !== placeholders(row[0])) throw new Error(`Interface placeholder mismatch: ${row[0]}`);
  catalogue[row[0]] = row.slice(1);
}
for (const [index, locale] of ["en", "es", "ja", "ko"].entries()) {
  const messages = Object.fromEntries(Object.keys(catalogue).sort().map(key => [key, catalogue[key][index]]));
  const path = join(directory, "locales", `${locale}.ts`);
  const expected = `// Generated by scripts/build-interface-locales.ts. Edit coreMessages / interfaceMessages.\nconst messages: Record<string, string> = ${JSON.stringify(messages, null, 2)};\nexport default messages;\n`;
  if (process.argv.includes("--check")) {
    if (await readFile(path,"utf8") !== expected) throw new Error(`Generated interface catalogue is stale: ${locale}`);
  } else await writeFile(path,expected);
}
console.log(JSON.stringify({ locales: 4, translatedMessages: Object.keys(catalogue).length }));
