import { useEffect, useRef, useState } from "react";
import type { EditProject } from "../domain/types";
import type { ProjectSession } from "../application/projectSession";
import type { ManualValueParticleRequestV1 } from "../application/manualValueParticlesV1";
import { createManualValueParticleInteractionV1, type ManualValueParticleApplicationV1, type ManualValueParticleStateV1 } from "../application/manualValueParticleInteractionV1";
import "./valueParticlesPanelV1.css";
type MaterialEvidence = Extract<ManualValueParticleRequestV1["value"], { kind: "material_evidence" }>["evidence"];
export interface ValueParticlesLabelsV1 {
  title: string; source: string; material: string; manual: string; amount: string; confirmation: string;
  note: string; add: string; cancel: string; idle: string; applying: string; done: string; cancelled: string;
  failed: string; uncertain: string; unavailable: string; locked: string; artPending: string; help: string;
}
export interface ValueParticlesPanelPropsV1 {
  project: EditProject; projectSession: ProjectSession; clipId: string;
  range: ManualValueParticleRequestV1["range"]; parameters: ManualValueParticleRequestV1["parameters"];
  /** Stable operation identity supplied by the existing host, never regenerated by read(). */
  operationId: string; createdAt: string; evidence?: MaterialEvidence; labels: ValueParticlesLabelsV1;
  disabled?: boolean;
  onApply?(application: ManualValueParticleApplicationV1): Promise<{ status: "applied" | "cancelled" }>;
  onPause?(): void;
}
/** Isolated source component. H13 supplies the sole existing command/Node bridge owner;
 * H15 registers reviewed copy. No shared mount, VA default or renderer is installed. */
export function ValueParticlesPanelV1(props: ValueParticlesPanelPropsV1) {
  const [mode, setMode] = useState<"material_evidence" | "user_asserted">(props.evidence ? "material_evidence" : "user_asserted");
  const [amount, setAmount] = useState(""), [confirmed, setConfirmed] = useState(false), [state, setState] = useState<ManualValueParticleStateV1>({ status: "idle" });
  const latest = useRef({ props, mode, amount, confirmed }); latest.current = { props, mode, amount, confirmed };
  const alive = useRef(true), interaction = useRef<ReturnType<typeof createManualValueParticleInteractionV1>>(undefined);
  if (!interaction.current) interaction.current = createManualValueParticleInteractionV1({
    read: () => {
      const s = latest.current, p = s.props;
      const value: ManualValueParticleRequestV1["value"] = s.mode === "material_evidence"
        ? { kind: "material_evidence", evidence: p.evidence! }
        : { kind: "user_asserted", quotedValue: s.amount.trim(), confirmed: true };
      return { project: p.project, projectSession: p.projectSession, hostOwner: p.onApply,
        disabled: p.disabled || (s.mode === "user_asserted" ? !s.confirmed || !s.amount.trim() : !p.evidence),
        request: { schema: "editkin.manual-value-particles/v1", expectedRevision: p.project.revision, id: p.operationId,
          clipId: p.clipId, range: p.range, parameters: p.parameters, createdAt: p.createdAt, value } };
    },
    apply: a => { const fn = latest.current.props.onApply; if (!fn) throw Error("MANUAL_VALUE_UI_UNAVAILABLE"); return fn(a); },
    onState: next => { if (alive.current) setState(next); }, onPause: () => latest.current.props.onPause?.(),
  });
  const driver = interaction.current;
  useEffect(() => { alive.current = true; driver.resume(); return () => { alive.current = false; driver.dispose(); }; }, []);
  useEffect(() => driver.invalidate(), [props.project, props.projectSession, props.clipId, props.evidence, props.range, props.parameters, props.operationId, props.createdAt, props.disabled, props.onApply, mode, amount, confirmed]);
  useEffect(() => props.projectSession.subscribe(() => driver.invalidate()), [props.projectSession]);
  const l = props.labels, busy = state.status === "applying", track = props.project.tracks.find(t => t.clips.some(c => c.id === props.clipId));
  const unavailable = !props.onApply || !track || track.kind !== "video" || track.hidden;
  const valid = mode === "material_evidence" ? !!props.evidence : confirmed && amount.trim().length > 0 && amount.trim().length <= 100;
  const status = track?.locked ? l.locked : unavailable ? l.unavailable : state.error ? String(state.error).includes("OUTCOME_UNKNOWN") ? l.uncertain : l.failed : l[state.status];
  return <section className="value-particles-panel-v1" aria-label={l.title} aria-busy={busy} data-state={state.status} data-testid="value-particles-panel"
    onKeyDown={e => { if (e.key === "Escape") { e.preventDefault(); e.stopPropagation(); driver.cancel(); } }}>
    <strong>{l.title}</strong>
    <label>{l.source}<select value={mode} disabled={busy || props.disabled} data-testid="value-basis" onChange={e => { driver.cancel(); setConfirmed(false); setMode(e.target.value as typeof mode); }}>
      <option value="material_evidence" disabled={!props.evidence}>{l.material}</option><option value="user_asserted">{l.manual}</option>
    </select></label>
    {mode === "material_evidence" ? <label>{l.amount}<output data-testid="value-evidence-amount">{props.evidence?.quotedValue ?? ""}</output></label>
      : <><label>{l.amount}<input type="text" maxLength={100} value={amount} disabled={busy || props.disabled} data-testid="value-amount"
        onChange={e => { setConfirmed(false); setAmount(e.target.value); }} /></label>
        <label className="value-particle-confirm"><input type="checkbox" checked={confirmed} disabled={busy || props.disabled} data-testid="value-confirm" onChange={e => setConfirmed(e.target.checked)} />{l.confirmation}</label></>}
    <p>{l.note}</p><p role="status" aria-live="polite" data-testid="value-status">{status}</p>
    <div className="value-particle-actions"><button type="button" disabled={!valid || busy || props.disabled || unavailable || track?.locked} data-testid="value-add" onClick={() => { void driver.apply(); }}>{l.add}</button>
      {busy && <button type="button" data-testid="value-cancel" onClick={() => driver.cancel()}>{l.cancel}</button>}</div>
    <small>{l.help}</small><small>{l.artPending}</small>
  </section>;
}
