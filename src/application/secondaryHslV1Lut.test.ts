import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join, resolve, sep } from "node:path";
import { createHash } from "node:crypto";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createEmptyProject } from "../domain/editGraph";
import { DEFAULT_COLOR, DEFAULT_TRANSFORM, type EditProject } from "../domain/types";
import { importColorLut, exportClipGradeCube } from "./creativeLibrary";
import { parseCubeFile, sampleParsedCube } from "../color/cubeLut";
import { prepareCompositeGrades } from "../render/ffmpegComposite";
import { buildRenderPlan } from "../render/planner";

let root = "", library = "";
beforeAll(async () => { root = await mkdtemp(join(tmpdir(), "editkin-secondary-hsl-library-")); library = join(root, "library"); });
afterAll(async () => {
  if (!root) return;
  if (!resolve(root).startsWith(resolve(tmpdir()) + sep) || !basename(root).startsWith("editkin-secondary-hsl-library-")) throw new Error("Unexpected owned test directory");
  await rm(root, { recursive: true });
});
function project(lut: { id: string; sha256: string }): EditProject {
  const value = createEmptyProject("Secondary HSL outside LUT", { width: 96, height: 48, fps: 30 });
  value.assets.push({ id: "a", name: "synthetic", uri: "synthetic.mkv", kind: "video", duration: 1, width: 96, height: 48 });
  value.tracks[0].clips.push({ id: "c", trackId: value.tracks[0].id, assetId: "a", timelineStart: 0, sourceStart: 0, duration: 1, volume: 0,
    transform: { ...DEFAULT_TRANSFORM }, color: { ...DEFAULT_COLOR }, keyframes: [], gradeV2: { schema: "editkin.color-grade/v2", nodes: [{ id: "secondary",
      secondaryHslV1: { schema: "editkin.secondary-hsl/v1", selectorSpace: "working_rgb_code", qualifier: { hue: { centerDegrees: 0, halfWidthDegrees: 20 } }, outside: { lut: { ...lut, strength: 1 } } } }] } });
  return value;
}
describe("secondary HSL outside LUT uses actual content-addressed library", () => {
  it("imports an owned fixture and exports the complete inside/outside65³ grade", async () => {
    const source = join(root, "synthetic.cube"), text = "LUT_3D_SIZE 2\n" + Array(8).fill("0.2 0.4 0.6").join("\n") + "\n";
    await writeFile(source, text, { flag: "wx" });
    const entry = await importColorLut(library, { sourcePath: source, name: "Synthetic test constant", license: "CC0-1.0", provenance: "Original numeric engineering fixture generated by this test", rightsBasis: "owner-authored", inputSpace: "rec709_display" });
    const value = project(entry), before = structuredClone(value), output = join(root, "secondary-grade.cube");
    const exported = await exportClipGradeCube(value, "c", output, library);
    const bytes = await readFile(output), cube = parseCubeFile(bytes.toString("utf8"));
    expect(exported.size).toBe(65);
    expect(exported.sha256).toBe(createHash("sha256").update(bytes).digest("hex"));
    expect(exported.omittedSpatial).toEqual([]);
    expect(sampleParsedCube(cube, [1, 0, 0])).toEqual([1, 0, 0]);
    sampleParsedCube(cube, [0, 1, 0]).forEach((component, index) => expect(component).toBeCloseTo([.2, .4, .6][index], 6));
    expect(value).toEqual(before);
    await expect(exportClipGradeCube(value, "c", output, library)).rejects.toThrow();
    expect((await readFile(output)).equals(bytes)).toBe(true);
  }, 30_000);
  it("normal composite loader requires an enabled outside LUT rather than silently ignoring it", async () => {
    const value = project({ id: "lut:3333333333333333", sha256: "3".repeat(64) });
    await expect(prepareCompositeGrades(value, buildRenderPlan(value, uri => uri))).rejects.toThrow();
    value.tracks[0].clips[0].gradeV2!.nodes![0].secondaryHslV1!.enabled = false;
    const disabled = await prepareCompositeGrades(value, buildRenderPlan(value, uri => uri));
    expect(disabled.stages.size).toBe(0);
    expect(disabled.workDirectory).toBeUndefined();
  });
});
