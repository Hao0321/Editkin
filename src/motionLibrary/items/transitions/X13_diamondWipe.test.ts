describe("X13 Diamond Wipe", () => {
  for (const [format, size] of Object.entries({ portrait: PORTRAIT, landscape: LANDSCAPE }) as Array<["portrait" | "landscape", MotionFrameSize]>) {
    it(`${format} matches its golden hashes at ${TIMES.join(", ")} s`, () => {
      expect(TIMES.map(t => { const f = frame(t, undefined, size); return sha256(`${f.matte}\n--overlay--\n${f.overlay ?? ""}`); })).toEqual(GOLDEN[format]);
    });
  }

  it("matte is strictly all A at t = 0 and all B at t = D, overlay empty, for every energy and duration", () => {
    for (const size of [PORTRAIT, LANDSCAPE]) {
      for (const energy of MOTION_ENERGIES) {
        for (const durationSeconds of DURATIONS) {
          const start = frame(0, { energy, durationSeconds }, size), end = frame(durationSeconds, { energy, durationSeconds }, size);
          expect([start.matte, start.overlay, end.matte, end.overlay]).toEqual([ALL_A(size), EMPTY(size), ALL_B(size), EMPTY(size)]);
        }
      }
    }
    expect(item().supportedDirections).toBeUndefined();
  });

  it("B covers half the frame at D/2 and crosses 50% inside 45–55% of the duration (every energy, duration, both formats)", () => {
    for (const size of [PORTRAIT, LANDSCAPE]) {
      for (const energy of MOTION_ENERGIES) {
        for (const durationSeconds of DURATIONS) {
          const input = { energy, durationSeconds }, label = `${energy} ${durationSeconds} ${size.width}`;
          expect(coverage(0.45 * durationSeconds, input, size), label).toBeLessThan(0.5);
          expect(Math.abs(coverage(0.5 * durationSeconds, input, size) - 0.5), label).toBeLessThan(0.01);
          expect(coverage(0.55 * durationSeconds, input, size), label).toBeGreaterThan(0.5);
        }
      }
    }
  });

  it("B only grows, in portrait and landscape", () => {
    for (const size of [PORTRAIT, LANDSCAPE]) {
      let previous = 0;
      for (let step = 1; step <= 20; step += 1) {
        const value = coverage((step / 20) * 0.5, undefined, size);
        expect(value).toBeGreaterThanOrEqual(previous - 1e-9);
        previous = value;
      }
      expect(previous).toBe(1);
    }
  });

  it("B is a 45° diamond centred on the frame, easing in from a point to the frame corners", () => {
    for (const size of [PORTRAIT, LANDSCAPE]) {
      const diamond = flattenPathD(pathDs(frame(0.2, undefined, size).matte)[0])[0];
      expect(diamond).toHaveLength(4);
      const [cx, cy] = [size.width / 2, size.height / 2];
      const r = Math.abs(diamond[0][0] - cx);
      for (const [x, y] of diamond) expect(Math.abs(x - cx) + Math.abs(y - cy)).toBeCloseTo(r, 1);
    }
    // The exact area helper: a diamond wholly inside (2r²) and one past the corners (the whole frame).
    expect(diamondAreaInFrame(300, LANDSCAPE)).toBeCloseTo(2 * 300 * 300, 3);
    expect(diamondAreaInFrame(960 + 540, LANDSCAPE)).toBeCloseTo(1920 * 1080, 3);
    const radii = Array.from({ length: 101 }, (_, index) => diamondRadius(index / 100, 700, 1500, 1.6));
    expect([radii[0], radii[100]]).toEqual([0, 1500]);
    expect(radii[50]).toBeCloseTo(700, 9);
    for (let index = 1; index <= 100; index += 1) expect(radii[index]).toBeGreaterThan(radii[index - 1]);
    expect((radii[51] - radii[50]) / (radii[50] - radii[49])).toBeCloseTo(1, 1);
  });

  it("runs an ink wave and a deep-shade wave ahead of B as concentric diamond bands (seeded order)", () => {
    const middle = frame(0.2);
    const bands = [...middle.overlay!.matchAll(/<path d="([^"]+)" fill="(#[0-9A-F]{6})" fill-rule="evenodd"\/>/g)];
    expect(bands).toHaveLength(2);
    const roles = diamondWaveRoles(1);
    expect(roles).toEqual(["ink", "accent2"]);
    expect([bands[0][2], bands[1][2]]).toEqual([palette()[roles[0]], palette()[roles[1]]]);
    // Outer band outside the inner band outside B: radii from the right-hand vertices of each diamond.
    const reach = (d: string) => flattenPathD(d).map(ring => Math.max(...ring.map(([x]) => x)) - 960);
    const [outer, innerHole] = reach(bands[0][1]), [inner, bHole] = reach(bands[1][1]);
    const b = reach(pathDs(middle.matte)[0])[0];
    expect(outer).toBeGreaterThan(inner);
    expect(inner).toBeGreaterThan(b);
    expect(innerHole).toBeCloseTo(inner - 1.5, 1);
    expect(bHole).toBeCloseTo(b - 1.5, 1);
    const orders = new Set(Array.from({ length: 8 }, (_, seed) => diamondWaveRoles(seed + 1).join("/")));
    expect(orders).toEqual(new Set(["ink/accent2", "accent2/ink"]));
    expect(frame(0.2, { palette: { ink: "#123456" } }).overlay).toContain('fill="#123456"');
  });

  it("is deterministic and generates a 1080×1920 frame well under the 20 ms budget (bound 60 ms)", () => {
    expect(frame(0.3, { seed: 7 }, PORTRAIT)).toEqual(frame(0.3, { seed: 7 }, PORTRAIT));
    frame(0.1, undefined, PORTRAIT);
    const started = performance.now();
    for (let index = 0; index < 30; index += 1) frame((index / 29) * 0.5, undefined, PORTRAIT);
    expect((performance.now() - started) / 30).toBeLessThan(60);
  });
});
