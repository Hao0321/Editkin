function notImplemented(id: string): never {
  throw new MotionLibraryNotImplementedError(id);
}

const implementationById = new Map<string, MotionLibraryImplementation>();
for (const implementation of IMPLEMENTATIONS) {
  if (implementationById.has(implementation.id)) throw new Error(`Duplicate motion library implementation ${implementation.id}`);
  implementationById.set(implementation.id, implementation);
}

/** Ids of the registered generators (IMPLEMENTATIONS), in registration order: tests derive the implemented set from it. */
export const MOTION_LIBRARY_IMPLEMENTATION_IDS: readonly string[] = Object.freeze(IMPLEMENTATIONS.map(implementation => implementation.id));

function implementationFor<K extends MotionLibraryKind>(id: string, kind: K): Extract<MotionLibraryImplementation, { kind: K }> | undefined {
  const implementation = implementationById.get(id);
  if (!implementation) return undefined;
  if (implementation.kind !== kind) throw new Error(`Motion library implementation ${id} is ${implementation.kind}, registered as ${kind}`);
  return implementation as Extract<MotionLibraryImplementation, { kind: K }>;
}

const freezeNames = (spec: { en: string; ja: string; zh: string }) => Object.freeze({ zh: spec.zh, ja: spec.ja, en: spec.en });

function showcasePlate(id: string): MotionShowcasePlate {
  return ACCENT_PLATE.has(id) ? "accent" : PAPER_PLATE.has(id) ? "paper" : "bg";
}

/** Claude's revision-pinned certification (certifications.ts); a placeholder without a generator is always pending. */
function artStatusFor(id: string, implementation: MotionLibraryImplementation | undefined): MotionArtStatus {
  return implementation ? motionArtStatus(id, resolveMotionItemRevision(implementation.revision)) : "pending";
}

function textItem(spec: TextSpec): TextMotionItem {
  const implementation = implementationFor(spec.id, "text");
  const defaultParams = Object.freeze(textMotionParamsSchema.parse({
    palette: MOTION_PALETTES[categoryTheme(spec.category)], energy: "standard", seed: 1, lines: [...spec.lines], font: spec.font ?? "display", durationSeconds: spec.duration,
  }));
  Object.freeze(defaultParams.lines); Object.freeze(defaultParams.palette);
  return Object.freeze({
    id: spec.id, kind: "text" as const, category: spec.category, names: freezeNames(spec), tags: Object.freeze([...spec.tags]),
    defaultParams, defaultDurationSeconds: spec.duration, ...(spec.loop ? { loopSeconds: spec.loop } : {}),
    previewText: spec.lines.join(" / "), showcasePlate: showcasePlate(spec.id), artStatus: artStatusFor(spec.id, implementation), implemented: Boolean(implementation),
    revision: resolveMotionItemRevision(implementation?.revision), ...(spec.notes ? { notes: spec.notes } : {}),
    generate: implementation?.generate ?? (() => notImplemented(spec.id)),
  });
}

function transitionItem(spec: TransitionSpec): TransitionMotionItem {
  const implementation = implementationFor(spec.id, "transition");
  const defaultParams = Object.freeze(transitionMotionParamsSchema.parse({
    palette: MOTION_PALETTES[categoryTheme(spec.category)], energy: "standard", seed: 1, durationSeconds: TRANSITION_DEFAULT_SECONDS,
  }));
  Object.freeze(defaultParams.palette);
  return Object.freeze({
    id: spec.id, kind: "transition" as const, category: spec.category, names: freezeNames(spec), tags: Object.freeze([...spec.tags]),
    defaultParams, defaultDurationSeconds: TRANSITION_DEFAULT_SECONDS, artStatus: artStatusFor(spec.id, implementation), implemented: Boolean(implementation),
    revision: resolveMotionItemRevision(implementation?.revision),
    ...(implementation?.supportedDirections ? { supportedDirections: implementation.supportedDirections } : {}),
    generate: implementation?.generate ?? (() => notImplemented(spec.id)),
  });
}

function backgroundItem(spec: BackgroundSpec): BackgroundMotionItem {
  const implementation = implementationFor(spec.id, "background");
  // A generator that declares its base loop must agree with the catalog (DESIGN §8: the period is computed, not guessed).
  if (implementation?.loopSeconds !== undefined && implementation.loopSeconds !== spec.loop) {
    throw new Error(`Background ${spec.id} generator loops every ${implementation.loopSeconds}s but the catalog says ${spec.loop}s`);
  }
  const defaultParams = Object.freeze(backgroundMotionParamsSchema.parse({
    palette: MOTION_PALETTES[categoryTheme(spec.category)], energy: "standard", seed: 1, durationSeconds: spec.loop, speed: 1, density: 1,
  }));
  Object.freeze(defaultParams.palette);
  return Object.freeze({
    id: spec.id, kind: "background" as const, category: spec.category, names: freezeNames(spec), tags: Object.freeze([...spec.tags]),
    defaultParams, defaultDurationSeconds: spec.loop, loopSeconds: spec.loop, loopCycles: implementation?.loopCycles ?? 1,
    artStatus: artStatusFor(spec.id, implementation), implemented: Boolean(implementation),
    revision: resolveMotionItemRevision(implementation?.revision),
    generate: implementation?.generate ?? (() => notImplemented(spec.id)),
  });
}

/** All 160 items in catalog order (T01–T80, X01–X40, B01–B40). */
export const MOTION_LIBRARY_CATALOG: readonly MotionLibraryItem[] = Object.freeze([
  ...TEXT.map(textItem), ...TRANSITIONS.map(transitionItem), ...BACKGROUNDS.map(backgroundItem),
]);

const ID_PATTERNS: Readonly<Record<MotionLibraryKind, RegExp>> = {
  text: /^T(0[1-9]|[1-7][0-9]|80)$/,
  transition: /^X(0[1-9]|[1-3][0-9]|40)$/,
  background: /^B(0[1-9]|[1-3][0-9]|40)$/,
};

const byId = new Map<string, MotionLibraryItem>();
for (const item of MOTION_LIBRARY_CATALOG) {
  if (byId.has(item.id)) throw new Error(`Duplicate motion library item ${item.id}`);
  if (!ID_PATTERNS[item.kind].test(item.id)) throw new Error(`Motion library id ${item.id} does not match its kind`);
  if (!MOTION_LIBRARY_CATEGORIES.some(category => category.id === item.category && category.kind === item.kind)) {
    throw new Error(`Motion library item ${item.id} has unknown category ${item.category}`);
  }
  byId.set(item.id, item);
}
for (const implementation of IMPLEMENTATIONS) if (!byId.has(implementation.id)) throw new Error(`Implementation ${implementation.id} is not registered`);
for (const kind of Object.keys(MOTION_LIBRARY_KIND_COUNTS) as MotionLibraryKind[]) {
  const count = MOTION_LIBRARY_CATALOG.filter(item => item.kind === kind).length;
  if (count !== MOTION_LIBRARY_KIND_COUNTS[kind]) throw new Error(`The motion library must register ${MOTION_LIBRARY_KIND_COUNTS[kind]} ${kind} items (found ${count})`);
}

export function findMotionLibraryItem(id: string): MotionLibraryItem | undefined {
  return byId.get(id);
}

export function getMotionLibraryItem(id: string): MotionLibraryItem {
  const item = byId.get(id);
  if (!item) throw new Error(`Unknown motion library item ${String(id)}`);
  return item;
}

export interface MotionLibraryFilter {
  readonly kind?: MotionLibraryKind;
  readonly category?: string;
  readonly implemented?: boolean;
  readonly artStatus?: "pending" | "certified";
}

export function listMotionLibraryItems(filter: MotionLibraryFilter = {}): readonly MotionLibraryItem[] {
  return MOTION_LIBRARY_CATALOG.filter(item => (filter.kind === undefined || item.kind === filter.kind)
    && (filter.category === undefined || item.category === filter.category)
    && (filter.implemented === undefined || item.implemented === filter.implemented)
    && (filter.artStatus === undefined || item.artStatus === filter.artStatus));
}

/** Items with a real generator (not the notImplemented placeholder). */
export function listImplemented(kind?: MotionLibraryKind): readonly MotionLibraryItem[] {
  return listMotionLibraryItems({ kind, implemented: true });
}

/**
 * The seamless period of a background at these params (DESIGN §8, backgroundLoop): the item's base loop,
 * stretched by 1, 2 or 4 so the speed gives a whole number of motion cycles. A clip whose length is a
 * multiple of this period loops without a seam; at speed 1 it is item.loopSeconds.
 */
export function motionBackgroundLoopSeconds(item: BackgroundMotionItem, params: Pick<BackgroundMotionParams, "speed">): number {
  return backgroundLoop(item.loopSeconds, item.loopCycles, params.speed).loopSeconds;
}
